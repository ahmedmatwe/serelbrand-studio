import { Agent, clamp, countWords } from './base.ts';
import type { Blueprint, FactCheckReport, Script, SeoPackage, ThumbnailConcept } from './schemas.ts';
import type { MediaAsset } from '../providers/media.ts';
import { spokenText } from './scriptwriter.ts';

export type Severity = 'low' | 'medium' | 'high' | 'critical';
export interface ComplianceIssue { check: string; severity: Severity; message: string; fix: string }
export type RiskLabel = 'Low risk' | 'Needs human review' | 'High risk' | 'Not suitable for publication';

export interface ComplianceInput {
  videoId: string;
  script: Script;
  factCheck: FactCheckReport;
  blueprint: Blueprint;
  thumbnails: ThumbnailConcept[];
  seo: SeoPackage;
  assets?: MediaAsset[];
  usesAIVoice: boolean;
  /** Realistic AI imagery/voice that viewers could mistake for real people/events. */
  usesRealisticSyntheticMedia: boolean;
  syntheticDisclosureSet: boolean;
  /** Set when a render exists: all frames are generated by the renderer itself. */
  renderVisualMode?: 'text-cards' | 'stock' | 'mixed';
}

export interface ComplianceReport {
  score: number;
  label: RiskLabel;
  issues: ComplianceIssue[];
  blockers: string[];
  requiresSyntheticDisclosure: boolean;
  copyrightStatus: 'clear' | 'needs_review' | 'violation';
  monetizationRisk: 'low' | 'medium' | 'high';
  disclaimer: string;
}

const PENALTY: Record<Severity, number> = { low: 2, medium: 6, high: 15, critical: 40 };

// Keyword lists are a first-pass heuristic only. They flag for human review; they do not replace it.
export const CLICKBAIT = ['لن تصدق', 'صادم', 'صدمة', 'فضيحة', 'مضمون', '100%', 'حصري', 'عاجل', 'سر خطير'];
const PROFANITY = ['لعنة', 'قذر', 'حقير', 'تافه'];
const HATE = ['حثالة', 'أعراق أدنى', 'يجب إبادة'];
const DANGEROUS = ['طريقة صنع قنبلة', 'تصنيع سلاح', 'جرعة قاتلة', 'انتحار', 'مخدرات', 'تفجير'];
const SENSITIVE = ['حرب', 'قتل', 'دماء', 'إرهاب', 'طائفي'];
const PII = [/\b\d{10,}\b/, /[\w.+-]+@[\w-]+\.[\w.]+/, /\+\d{6,}/];

/** Words in the spoken text that risk policy strikes or demonetization (fixed at the script stage). */
export function policyHits(text: string): { word: string; kind: 'hate' | 'dangerous' | 'profanity' | 'pii' }[] {
  const out: { word: string; kind: 'hate' | 'dangerous' | 'profanity' | 'pii' }[] = [];
  for (const w of HATE) if (text.includes(w)) out.push({ word: w, kind: 'hate' });
  for (const w of DANGEROUS) if (text.includes(w)) out.push({ word: w, kind: 'dangerous' });
  for (const w of PROFANITY) if (text.includes(w)) out.push({ word: w, kind: 'profanity' });
  for (const re of PII) { const m = text.match(re); if (m) out.push({ word: m[0], kind: 'pii' }); }
  return out;
}
const ALLOWED_LICENSES = new Set(['generated-owned', 'pexels', 'pixabay', 'cc0', 'licensed']);

/** Light Arabic stemming: strip diacritics and common prefixes (و ف ب ك ل ال) when enough of the word remains. */
export function normalizeWord(w: string): string {
  const bare = w.replace(/\p{M}/gu, '');
  const stripped = bare.replace(/^(?:[وف])?(?:[بكل])?(?:ال)?/, '');
  return stripped.length >= 3 ? stripped : bare;
}
const contentWords = (t: string) => (t.match(/[\p{L}\p{M}\p{N}]{3,}/gu) ?? []).map(normalizeWord);

/** Share of title content-words that actually appear in the script. Low => potentially misleading title. */
export function titleSupport(title: string, script: string): number {
  const tw = contentWords(title);
  if (!tw.length) return 1;
  const body = new Set(contentWords(script));
  return tw.filter((w) => body.has(w)).length / tw.length;
}

/** Fraction of duplicate sentences — a proxy for repetitive, low-value generated text. */
export function duplicateSentenceRatio(text: string): number {
  const sentences = text.split(/[.!؟?\n،]+/).map((s) => s.trim()).filter((s) => countWords(s) >= 4);
  if (!sentences.length) return 0;
  return 1 - new Set(sentences).size / sentences.length;
}

export function checkCompliance(input: ComplianceInput): ComplianceReport {
  const issues: ComplianceIssue[] = [];
  const add = (check: string, severity: Severity, message: string, fix: string) => issues.push({ check, severity, message, fix });
  const text = spokenText(input.script);
  const titleAndThumb = [input.seo.primaryTitle, ...input.thumbnails.map((t) => t.text)].join(' ');

  // Copyright: assets and music
  const badAssets = (input.assets ?? []).filter((a) => !ALLOWED_LICENSES.has(a.license));
  for (const a of badAssets) add('copyright.asset', 'critical', `Asset ${a.id} has license "${a.license}"`, 'Replace with owned, generated, or properly licensed media');
  const stock = (input.assets ?? []).filter((a) => a.license === 'pexels' || a.license === 'pixabay');
  if (stock.length) add('rights.stock_review', 'low', `${stock.length} stock clips used`, 'Check no identifiable person/brand appears to endorse the content (Pexels license); credits are added to the description');
  if (input.blueprint.music.source === 'none') add('copyright.music', 'low', 'No background music planned', 'Optional: add music from YouTube Audio Library');
  if (/(فيلم|مسلسل|مباراة|قناة|برنامج تلفزيوني).{0,20}(مقطع|لقطة)/.test(input.blueprint.scenes.map((s) => s.footage).join(' ')))
    add('copyright.footage', 'high', 'Blueprint references third-party broadcast footage', 'Use original graphics or licensed stock instead');

  // Facts
  if (input.factCheck.overall === 'blocked') add('facts.unverified', 'critical', 'At least one factual claim has no source', 'Add a real source or remove the claim');
  else if (input.factCheck.overall === 'needs_review') add('facts.review', 'high', 'Some claims need human verification', 'Verify flagged claims and replace mock/weak sources');
  for (const q of input.factCheck.claims.filter((c) => c.type === 'quote' && c.status !== 'verified'))
    add('impersonation.quote', 'high', `Unverified quote: "${q.claim.slice(0, 60)}"`, 'Verify verbatim from a primary source or remove');

  // Packaging honesty
  const support = titleSupport(input.seo.primaryTitle, text);
  if (support < 0.4) add('packaging.misleading_title', 'high', `Only ${(support * 100).toFixed(0)}% of title keywords appear in the script`, 'Align the title with what the video actually covers');
  for (const w of CLICKBAIT) if (titleAndThumb.includes(w)) add('packaging.clickbait', 'medium', `Clickbait phrase "${w}" in title/thumbnail`, 'Use a specific, truthful promise instead');
  for (const t of input.thumbnails.filter((x) => !x.valid)) add('packaging.thumbnail', 'medium', `Thumbnail "${t.text}": ${t.problems.join('; ')}`, 'Fix or drop this concept');

  // Harmful / sensitive content
  for (const w of HATE) if (text.includes(w)) add('policy.hate', 'critical', `Possible hate speech: "${w}"`, 'Remove');
  for (const w of DANGEROUS) if (text.includes(w)) add('policy.dangerous', 'high', `Possibly dangerous/sensitive topic: "${w}"`, 'Human review for policy and age restriction');
  for (const w of SENSITIVE) if (text.includes(w)) add('ads.sensitive', 'low', `Sensitive word "${w}" may limit ads`, 'Keep it factual and non-graphic');
  for (const w of PROFANITY) if (text.includes(w)) add('ads.profanity', 'medium', `Profanity "${w}"`, 'Replace with neutral wording');
  for (const re of PII) if (re.test(text)) add('privacy.pii', 'high', 'Script may contain personal contact data', 'Remove phone numbers / emails');

  // Reused / low-value repetitive content
  const dup = duplicateSentenceRatio(text);
  if (dup > 0.15) add('originality.repetitive', 'high', `${(dup * 100).toFixed(0)}% duplicate sentences`, 'Rewrite repeated passages; add original analysis');
  const original = input.renderVisualMode
    ? input.renderVisualMode !== 'stock'
    : input.blueprint.scenes.some((s) => s.assetSource === 'original-graphic' || s.assetSource === 'screen-recording');
  if (input.usesAIVoice && !original) add('originality.ai_only', 'medium', 'AI voice + no original visuals: higher "inauthentic content" risk', 'Add original graphics, charts, or analysis segments');

  // Synthetic media disclosure
  const requiresSyntheticDisclosure = input.usesRealisticSyntheticMedia;
  if (requiresSyntheticDisclosure && !input.syntheticDisclosureSet)
    add('disclosure.synthetic', 'critical', 'Realistic synthetic media without YouTube "altered or synthetic content" disclosure', 'Enable the disclosure flag on upload');

  const score = Math.round(clamp(100 - issues.reduce((s, i) => s + PENALTY[i.severity], 0)));
  const has = (s: Severity) => issues.some((i) => i.severity === s);
  const label: RiskLabel = has('critical') ? 'Not suitable for publication' : score < 70 ? 'High risk' : has('high') || score < 90 ? 'Needs human review' : 'Low risk';

  const blockers = issues.filter((i) => i.severity === 'critical' || i.check.startsWith('facts.') || i.check === 'packaging.misleading_title' || i.check.startsWith('copyright.') && i.severity !== 'low').map((i) => `${i.check}: ${i.message}`);
  if (score < 90) blockers.unshift(`Compliance score ${score} < 90`);

  return {
    score,
    label,
    issues,
    blockers,
    requiresSyntheticDisclosure,
    copyrightStatus: issues.some((i) => i.check.startsWith('copyright.') && i.severity === 'critical') ? 'violation' : issues.some((i) => i.check.startsWith('copyright.') && i.severity !== 'low') ? 'needs_review' : 'clear',
    monetizationRisk: has('critical') || issues.filter((i) => i.check.startsWith('ads.') || i.check.startsWith('policy.')).length >= 3 ? 'high' : issues.some((i) => i.check.startsWith('ads.') || i.check.startsWith('policy.') || i.check.startsWith('originality.')) ? 'medium' : 'low',
    disclaimer: 'Automated heuristic scan. It reduces risk but cannot guarantee YouTube acceptance or monetization.',
  };
}

export class ComplianceAgent extends Agent<ComplianceInput, ComplianceReport> {
  readonly name = 'compliance';
  readonly artifactKind = 'compliance_report';
  protected async execute(input: ComplianceInput) {
    return checkCompliance(input);
  }
}
